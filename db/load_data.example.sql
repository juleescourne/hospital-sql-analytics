USE hospital_analytics;

LOAD DATA LOCAL INFILE 'C:/ABSOLUTE/PATH/organizations.csv'
INTO TABLE organizations
FIELDS TERMINATED BY ','
OPTIONALLY ENCLOSED BY '"'
LINES TERMINATED BY '\n'
IGNORE 1 LINES
(@Id, @NAME, @ADDRESS, @CITY, @STATE, @ZIP)
SET
    Id = NULLIF(@Id, ''),
    NAME = NULLIF(@NAME, ''),
    ADDRESS = NULLIF(@ADDRESS, ''),
    CITY = NULLIF(@CITY, ''),
    STATE = NULLIF(@STATE, ''),
    ZIP = NULLIF(TRIM(TRAILING '\r' FROM @ZIP), '');

