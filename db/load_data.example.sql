LOAD DATA LOCAL INFILE 'C:/ABSOLUTE/PATH/encounters.csv'
INTO TABLE encounters
FIELDS TERMINATED BY ','
OPTIONALLY ENCLOSED BY '"'
LINES TERMINATED BY '\n'
IGNORE 1 LINES
(
    @Id,
    @START,
    @STOP,
    @PATIENT,
    @ORGANIZATION,
    @PAYER,
    @ENCOUNTERCLASS,
    @CODE,
    @DESCRIPTION,
    @BASE_ENCOUNTER_COST,
    @TOTAL_CLAIM_COST,
    @PAYER_COVERAGE,
    @REASONCODE,
    @REASONDESCRIPTION
)
SET
    Id = NULLIF(@Id, ''),
    START = STR_TO_DATE(REPLACE(REPLACE(@START, 'T', ' '), 'Z', ''), '%Y-%m-%d %H:%i:%s'),
